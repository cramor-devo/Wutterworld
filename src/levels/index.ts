export type NextStep = { type: 'level'; id: string } | { type: 'story'; id: string };

export interface LevelDef {
  id: string;
  name: string;
  place: string;
  /** Hits never cost hearts (tutorial). */
  safe: boolean;
  /** Underwater reef, or dry land (beach, night market) with a water tank and land gravity when dry. */
  setting: LevelSetting;
  music: SongId;
  map: readonly string[];
  signs: readonly string[];
  /** Extra enemies that only appear on hard difficulty (tile column/row, like the map). */
  hardEnemies?: readonly HardEnemy[];
  /** Map columns under a roof (Jiufen's Jishan Street): the scene draws the roof, shop fronts and a darker lane. */
  covered?: { from: number; to: number };
  next: NextStep;
}

export interface HardEnemy {
  kind: EnemyKind;
  col: number;
  row: number;
}

