export const FONT_CHARS = Object.keys(GLYPHS).join('');

/** Uppercases and replaces characters the font cannot draw with a space. */
export function toFontText(text: string): string {
  return [...text.toUpperCase()].map((ch) => (ch === '\n' || GLYPHS[ch] ? ch : ' ')).join('');
}
