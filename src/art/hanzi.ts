/** Draws `text` one glyph after another with `gap` px between glyphs, top-left at `x`, `y`. */
export function drawHanzi(ctx: CanvasRenderingContext2D, text: string, x: number, y: number, color: string, gap = 1, vertical = false): void {
  ctx.fillStyle = color;
  [...text].forEach((ch, i) => {
    const glyph = HANZI[ch];
    if (!glyph) throw new Error(`No pixel glyph for '${ch}'`);
    const ox = vertical ? x : x + i * (HANZI_SIZE + gap);
    const oy = vertical ? y + i * (HANZI_SIZE + gap) : y;
    glyph.forEach((row, r) => {
      for (let c = 0; c < row.length; c++) if (row[c] === '#') ctx.fillRect(ox + c, oy + r, 1, 1);
    });
  });
}

/** Pixel width of a horizontal line of glyphs. */
export function hanziWidth(text: string, gap = 1): number {
  const n = [...text].length;
  return n * HANZI_SIZE + Math.max(0, n - 1) * gap;
}
